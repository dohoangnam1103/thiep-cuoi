#!/usr/bin/env node
// Regenerates packages/invitation-core/src/demo-shell/keyframes.ts from the
// site-2 global stylesheet. Rerun after porting more CSS from master.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(
  path.join(ROOT, "apps/site-2/src/app/globals.css"),
  "utf8",
);

const blocks = [];
for (const m of css.matchAll(/@keyframes\s+[a-zA-Z0-9_-]+\s*\{/g)) {
  let depth = 0;
  let k = css.indexOf("{", m.index) + 1;
  depth = 1;
  while (depth > 0) {
    if (css[k] === "{") depth += 1;
    else if (css[k] === "}") depth -= 1;
    k += 1;
  }
  blocks.push(css.slice(m.index, k));
}

function extractLayer(name) {
  const start = css.search(new RegExp(`@layer\\s+${name}\\s*\\{`));
  if (start < 0) return "";
  let depth = 1;
  let k = css.indexOf("{", start) + 1;
  while (depth > 0) {
    if (css[k] === "{") depth += 1;
    else if (css[k] === "}") depth -= 1;
    k += 1;
  }
  return css.slice(start, k);
}

const out = `// Auto-generated by scripts/extract-demo-keyframes.mjs. Do not edit by hand.
// The demo shell references this CSS ONLY from React inline styles and custom
// classNames that route CSS splitting cannot trace, so per-route chunks drop
// it. Rendering it here guarantees it exists wherever the demo shell mounts.
export const DEMO_SHELL_KEYFRAMES = \`
${blocks.join("\n")}
\`;
export const DEMO_SHELL_LAYER_CSS = \`
${extractLayer("base")}
${extractLayer("utilities")}
\`;
`;
writeFileSync(
  path.join(ROOT, "packages/invitation-core/src/demo-shell/keyframes.ts"),
  out,
);
console.log(`wrote ${blocks.length} keyframes (${out.length} bytes)`);
