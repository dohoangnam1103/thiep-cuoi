#!/usr/bin/env node
// One-off generator: builds packages/invitation-core/src/templates/index.tsx
// (dynamic registry for the full template catalog) from the master maps.
// Rerun after adding templates: node scripts/generate-site2-template-registry.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(path.join(ROOT, p), "utf8");

const demo = read("src/components/chungdoi-demo.tsx");
const generated = read("src/components/generated/template-renderers.tsx");

// const X = dynamic(() => import("@/components/FILE").then((m) => m.EXPORT));
const dynMap = new Map();
for (const m of demo.matchAll(
  /const (\w+) = dynamic\(\(\) => import\("@\/components\/([^"]+)"\)\.then\(\(\w+\) => \w+\.(\w+)\)\)/g,
)) {
  dynMap.set(m[1], { file: m[2], export: m[3] });
}
// "slug": templateRendererEntry(X,
const entries = [];
for (const m of demo.matchAll(/"([a-z0-9-]+)": templateRendererEntry\((\w+),/g)) {
  entries.push({ slug: m[1], constName: m[2] });
}
// generated file pieces
const genMods = new Map();
for (const m of generated.matchAll(
  /const (TemplateRenderer\d+) = dynamic\(\(\) => import\("@\/components\/([^"]+)"\)\.then\(\(\w+\) => \w+\.(\w+)\)\)/g,
)) {
  genMods.set(m[1], { file: m[2], export: m[3] });
}
for (const m of generated.matchAll(/"([a-z0-9-]+)": \{ component: (TemplateRenderer\d+),/g)) {
  entries.push({ slug: m[1], gen: m[2] });
}

const SKIP = new Set(["jasmine-white", "silk-flora-brown"]);
// Retired slugs stay out of the site-2 catalog (unknown URLs 404).
const retiredSrc = read("packages/invitation-data/src/chungdoi.ts");
const retiredMatch = retiredSrc.match(/retiredTemplateSlugs = new Set<string>\(\[([\s\S]*?)\]\);/);
const RETIRED = new Set(
  retiredMatch ? [...retiredMatch[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]) : [],
);
const seen = new Set();
const lines = [];
lines.push(`"use client";`);
lines.push(``);
lines.push(`// Auto-generated by scripts/generate-site2-template-registry.mjs. Do not edit by hand.`);
lines.push(`import dynamic from "next/dynamic";`);
lines.push(``);
lines.push(`export {`);
lines.push(`  JasmineWhiteInvitation,`);
lines.push(`  SilkFloraBrownInvitation,`);
lines.push(`  getSignatureRenderer,`);
lines.push(`  SIGNATURE_RENDERER_SLUGS,`);
lines.push(`} from "../signature/index";`);
lines.push(`export type { InvitationRenderContent } from "../signature/types";`);
lines.push(``);

const slugs = ["jasmine-white", "silk-flora-brown"];
for (const e of entries) {
  if (SKIP.has(e.slug) || RETIRED.has(e.slug) || seen.has(e.slug)) continue;
  let mod;
  if (e.gen) {
    mod = genMods.get(e.gen);
  } else {
    mod = dynMap.get(e.constName);
  }
  if (!mod) {
    console.error(`no module for slug ${e.slug}`);
    process.exitCode = 1;
    continue;
  }
  seen.add(e.slug);
  slugs.push(e.slug);
  const varName = `Template_${e.slug.replace(/-/g, "_")}`;
  lines.push(
    `const ${varName} = dynamic(() => import("./${mod.file}").then((m) => m.${mod.export}));`,
  );
}
// physical-experience specials (direct invitations, no envelope lab on site-2)
const specials = [
  ["long-phung-gatefold", "./gatefold/long-phung-gatefold-invitation", "LongPhungGatefoldInvitation"],
  ["nguyet-anh-sleeve", "./sleeve/nguyet-anh-sleeve-invitation", "NguyetAnhSleeveInvitation"],
  ["doraemon-door", "./doraemon-door/doraemon-door-invitation", "DoraemonDoorInvitation"],
];
for (const [slug, file, exp] of specials) {
  if (RETIRED.has(slug) || seen.has(slug)) continue;
  seen.add(slug);
  slugs.push(slug);
  const varName = `Template_${slug.replace(/-/g, "_")}`;
  lines.push(`const ${varName} = dynamic(() => import("${file}").then((m) => m.${exp}));`);
}
lines.push(``);
slugs.sort();
lines.push(`export const TEMPLATE_RENDERER_SLUGS = [`);
for (const s of slugs) lines.push(`  "${s}",`);
lines.push(`] as const;`);
lines.push(``);
lines.push(`export type TemplateRendererSlug = (typeof TEMPLATE_RENDERER_SLUGS)[number];`);
lines.push(``);
lines.push(`const RENDERERS: Record<string, React.ComponentType<{ content: import("../signature/types").InvitationRenderContent }> | undefined> = {`);
lines.push(`  "jasmine-white": undefined,`);
lines.push(`  "silk-flora-brown": undefined,`);
for (const s of slugs) {
  if (s === "jasmine-white" || s === "silk-flora-brown") continue;
  lines.push(`  "${s}": Template_${s.replace(/-/g, "_")} as never,`);
}
lines.push(`};`);
lines.push(``);
lines.push(`import { getSignatureRenderer } from "../signature/index";`);
lines.push(``);
lines.push(`export function getTemplateRenderer(slug: string) {`);
lines.push(`  return getSignatureRenderer(slug) ?? RENDERERS[slug];`);
lines.push(`}`);
lines.push(``);

writeFileSync(
  path.join(ROOT, "packages/invitation-core/src/templates/index.tsx"),
  lines.join("\n"),
);
console.log(`wrote registry with ${slugs.length} slugs`);

// Pure catalog for availability checks (no client imports).
const catalog = [
  `// Auto-generated by scripts/generate-site2-template-registry.mjs. Do not edit by hand.`,
  `export const TEMPLATE_CATALOG_SLUGS = [`,
  ...slugs.map((s) => `  "${s}",`),
  `] as const;`,
  ``,
  `export type TemplateCatalogSlug = (typeof TEMPLATE_CATALOG_SLUGS)[number];`,
  ``,
  `const CATALOG_SET: ReadonlySet<string> = new Set(TEMPLATE_CATALOG_SLUGS);`,
  ``,
  `export function isCatalogTemplate(slug: string): boolean {`,
  `  return CATALOG_SET.has(slug);`,
  `}`,
  ``,
];
writeFileSync(
  path.join(ROOT, "packages/invitation-data/src/template-catalog.ts"),
  catalog.join("\n"),
);
console.log(`wrote catalog with ${slugs.length} slugs`);
